import { getCliClient } from 'sanity/cli';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
process.loadEnvFile('.env.local');
const client = getCliClient({ projectId: process.env.NEXT_PUBLIC_SANITY_PROJECT_ID, apiVersion: '2024-01-01', useCdn: false }).withConfig({ dataset: 'development', perspective: 'raw' });
assert.equal(client.config().projectId, 'yzaa35ug');
assert.equal(client.config().dataset, 'development');
const docs = await client.fetch('*[_type == "departemen" && slug.current == "psdm"]');
assert.equal(docs.length, 1, 'Inspect drafts before updating');
const doc = docs[0];
assert.equal(doc.fullName, 'Departemen Pengembangan Sumber Daya Manusia');
const fullName = 'Departemen Pengembangan Sumber Daya Mahasiswa';
writeFileSync('.codex-attachments/psdm-name-20261105/before.json', JSON.stringify(doc, null, 2), { flag: 'wx' });
await client.patch(doc._id).ifRevisionId(doc._rev).set({ fullName }).commit();
const after = await client.getDocument(doc._id);
assert.equal(after.fullName, fullName);
const stable = ({ fullName, _rev, _updatedAt, ...rest }) => rest;
assert.deepEqual(stable(after), stable(doc));
console.log(JSON.stringify({ dataset: 'development', id: doc._id, fullName: after.fullName, onlyNameChanged: true }));
