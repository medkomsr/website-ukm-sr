import { getCliClient } from 'sanity/cli';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
process.loadEnvFile('.env.local');
const client = getCliClient({ projectId: process.env.NEXT_PUBLIC_SANITY_PROJECT_ID, apiVersion: '2024-01-01', useCdn: false }).withConfig({ dataset: 'development', perspective: 'raw' });
assert.equal(client.config().projectId, 'yzaa35ug');
assert.equal(client.config().dataset, 'development');
const doc = await client.getDocument('bidang-dia');
assert.ok(doc);
assert.equal(await client.getDocument('drafts.bidang-dia'), undefined);
const target = doc.gallery.find(item => item._key === 'dia-documentation-5');
assert.ok(target);
const asset = await client.getDocument(target.image.asset._ref);
assert.equal(asset.originalFilename, '20251025_214016.jpg');
writeFileSync('.codex-attachments/dia-gallery-20261105/before-remove-fifth.json', JSON.stringify(doc, null, 2), { flag: 'wx' });
await client.patch(doc._id).ifRevisionId(doc._rev).unset(['gallery[_key=="dia-documentation-5"]']).commit();
const after = await client.getDocument(doc._id);
const expected = { ...doc, gallery: doc.gallery.filter(item => item._key !== target._key) };
const stable = ({ _rev, _updatedAt, ...rest }) => rest;
assert.deepEqual(stable(after), stable(expected));
assert.equal(after.gallery.length, 4);
console.log(JSON.stringify({ dataset: 'development', removed: asset.originalFilename, photos: after.gallery.length, verified: true }));
