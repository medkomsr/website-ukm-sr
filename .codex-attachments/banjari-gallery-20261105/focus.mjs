import { getCliClient } from 'sanity/cli';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
process.loadEnvFile('.env.local');
const client = getCliClient({ projectId: process.env.NEXT_PUBLIC_SANITY_PROJECT_ID, apiVersion: '2024-01-01', useCdn: false }).withConfig({ dataset: 'development', perspective: 'raw' });
assert.equal(client.config().projectId, 'yzaa35ug');
assert.equal(client.config().dataset, 'development');
const id = 'bidang-banjari-nasyid';
const doc = await client.getDocument(id);
assert.ok(doc);
assert.equal(await client.getDocument(`drafts.${id}`), undefined);
const key = 'banjari-documentation-1';
const first = doc.gallery.find(item => item._key === key);
assert.ok(first);
writeFileSync('.codex-attachments/banjari-gallery-20261105/before-focus.json', JSON.stringify(doc, null, 2), { flag: 'wx' });
const hotspot = { _type: 'sanity.imageHotspot', x: 0.5, y: 0.85, width: 1, height: 0.3 };
await client.patch(id).ifRevisionId(doc._rev).set({ [`gallery[_key=="${key}"].image.hotspot`]: hotspot }).commit();
const after = await client.getDocument(id);
const expected = structuredClone(doc);
expected.gallery.find(item => item._key === key).image.hotspot = hotspot;
const stable = ({ _rev, _updatedAt, ...rest }) => rest;
assert.deepEqual(stable(after), stable(expected));
console.log(JSON.stringify({ dataset: 'development', photo: key, hotspot, verified: true }));
